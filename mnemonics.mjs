const normalize=s=>String(s??'').normalize('NFKC').toLocaleLowerCase('de').trim().replace(/\s+/g,' ').replace(/[.!?]+$/,'');
export function wordMnemonic(word){
 const key=normalize(word.ko);
 if(!Object.hasOwn(entries,key))return null;
 const entry=entries[key];
 const answers=[word.en,word.de].flatMap(s=>String(s||'').split(';')).map(normalize);
 // Gleich geschriebene Wörter können andere Bedeutungen haben (z. B. 차 = Auto).
 if(!entry.senses.some(s=>answers.includes(normalize(s))))return null;
 return entry;
}
